import AgentVMModels
import Foundation

// MARK: - Bidirectional Declarative Topology Codec (.avm.hcl & compose.yaml)

public struct TopologyIACCodec: Sendable {
    public init() {}

    // MARK: - Export [VMSpec] + Policy to Declarative .avm.hcl

    public func exportHCL(vms: [VMSpec], policy: FirewallPolicySet?) -> String {
        var lines: [String] = []
        lines.append("# AgentVM Declarative Fleet Specification (.avm.hcl)")
        lines.append("# Generated by AgentVM v\(SemanticVersion.current.description)")
        lines.append("")

        if let policy {
            lines.append("firewall_policy \"\(sanitizeIdentifier(policy.id.rawValue))\" {")
            lines.append("  name           = \"\(escapeQuoted(policy.name))\"")
            lines.append("  default_egress = \"\(policy.defaultEgressVerdict.rawValue)\"")
            lines.append("  block_metadata = \(policy.blockPrivateMetadataIPs ? "true" : "false")")
            for rule in policy.rules.sorted(by: { $0.priority < $1.priority }) {
                lines.append("")
                lines.append("  rule \"\(sanitizeIdentifier(rule.id.rawValue))\" {")
                lines.append("    priority = \(rule.priority)")
                lines.append("    name     = \"\(escapeQuoted(rule.name))\"")
                lines.append("    verdict  = \"\(rule.verdict.rawValue)\"")
                let conds = rule.conditions.map { "\"\(escapeQuoted($0.humanReadableSummary))\"" }.joined(separator: ", ")
                lines.append("    match    = [\(conds)]")
                lines.append("  }")
            }
            lines.append("}")
            lines.append("")
        }

        for vm in vms {
            lines.append("sandbox_vm \"\(sanitizeIdentifier(vm.name))\" {")
            lines.append("  id          = \"\(escapeQuoted(vm.id.rawValue))\"")
            lines.append("  agent_owner = \"\(escapeQuoted(vm.agentOwnerTag))\"")
            lines.append("  guest_os    = \"\(vm.guestOS.rawValue)\"")
            lines.append("  vcpus       = \(vm.compute.vcpuCount)")
            lines.append("  memory_mb   = \(vm.compute.memoryMB)")
            lines.append("  balloon_min = \(vm.compute.minBalloonMemoryMB)")
            lines.append("  max_minutes = \(vm.maxRuntimeMinutes)")

            if let nic = vm.networkInterfaces.first {
                lines.append("")
                lines.append("  network {")
                lines.append("    mode    = \"\(nic.mode.rawValue)\"")
                lines.append("    ipv4    = \"\(nic.ipv4Address)\"")
                lines.append("    subnet  = \"\(nic.subnetCIDR)\"")
                lines.append("    gateway = \"\(nic.gatewayIPv4)\"")
                lines.append("    mac     = \"\(nic.macAddress)\"")
                lines.append("  }")
            }

            for mount in vm.virtioFSMounts {
                lines.append("")
                lines.append("  virtiofs \"\(sanitizeIdentifier(mount.mountTag))\" {")
                lines.append("    host_path   = \"\(escapeQuoted(ByteMetricsFormatter.scrubHomePath(mount.hostDirectoryPath)))\"")
                lines.append("    guest_mount = \"\(escapeQuoted(mount.guestMountPoint))\"")
                lines.append("    read_only   = \(mount.readOnly ? "true" : "false")")
                lines.append("  }")
            }

            for fwd in vm.portForwards {
                lines.append("")
                lines.append("  port_forward \"\(sanitizeIdentifier(fwd.label))\" {")
                lines.append("    host_port  = \(fwd.hostPort)")
                lines.append("    guest_port = \(fwd.guestPort)")
                lines.append("    transport  = \"\(fwd.protocolType.rawValue)\"")
                lines.append("  }")
            }

            lines.append("}")
            lines.append("")
        }

        return lines.joined(separator: "\n")
    }

    // MARK: - Parse .avm.hcl into [VMSpec]

    public func importHCL(_ source: String, defaultDiskDirectory: URL) throws -> [VMSpec] {
        var specs: [VMSpec] = []
        let rawLines = source.components(separatedBy: .newlines)

        var currentVMName: String?
        var kv: [String: String] = [:]
        var mounts: [VirtioFSMountSpec] = []
        var forwards: [PortForwardRuleSpec] = []
        var nestedKind: String?
        var nestedName: String = ""
        var nestedKV: [String: String] = [:]
        var braceDepth = 0

        for rawLine in rawLines {
            let trimmed = rawLine.trimmingCharacters(in: .whitespaces)
            if trimmed.isEmpty || trimmed.hasPrefix("#") || trimmed.hasPrefix("//") {
                continue
            }

            if braceDepth == 0, trimmed.hasPrefix("sandbox_vm ") && trimmed.hasSuffix("{") {
                currentVMName = extractQuotedToken(from: trimmed) ?? "imported-vm"
                kv = [:]
                mounts = []
                forwards = []
                braceDepth = 1
                continue
            }

            guard currentVMName != nil else {
                // Skip non-VM blocks like firewall_policy while tracking braces
                if trimmed.hasSuffix("{") { braceDepth += 1 }
                if trimmed == "}" { braceDepth = max(0, braceDepth - 1) }
                continue
            }

            if braceDepth == 1 && trimmed.hasSuffix("{") {
                let parts = trimmed.split(separator: " ", omittingEmptySubsequences: true)
                nestedKind = parts.first.map(String.init)
                nestedName = extractQuotedToken(from: trimmed) ?? "item"
                nestedKV = [:]
                braceDepth = 2
                continue
            }

            if trimmed == "}" {
                if braceDepth == 2 {
                    if nestedKind == "virtiofs" {
                        mounts.append(VirtioFSMountSpec(
                            mountTag: String(nestedName.prefix(36)),
                            hostDirectoryPath: nestedKV["host_path"] ?? "/tmp",
                            guestMountPoint: nestedKV["guest_mount"] ?? "/mnt/\(nestedName)",
                            readOnly: nestedKV["read_only"] == "true"
                        ))
                    } else if nestedKind == "port_forward" {
                        let hp = UInt16(nestedKV["host_port"] ?? "8080") ?? 8080
                        let gp = UInt16(nestedKV["guest_port"] ?? "8080") ?? 8080
                        let proto = PortForwardProtocol(rawValue: nestedKV["transport"] ?? "") ?? .vsockStream
                        forwards.append(PortForwardRuleSpec(
                            label: nestedName,
                            protocolType: proto,
                            hostPort: hp,
                            guestPort: gp
                        ))
                    } else if nestedKind == "network" {
                        for (k, v) in nestedKV {
                            kv["net.\(k)"] = v
                        }
                    }
                    nestedKind = nil
                    braceDepth = 1
                } else if braceDepth == 1, let vmName = currentVMName {
                    let vmID = kv["id"].map { VMID($0) } ?? VMID.generate(prefix: "vm")
                    let guestOS = GuestOSType(rawValue: kv["guest_os"] ?? "") ?? .linuxARM64
                    let vcpus = Int(kv["vcpus"] ?? "") ?? guestOS.defaultVCPUs
                    let memMB = UInt64(kv["memory_mb"] ?? "") ?? guestOS.defaultMemoryMB
                    let balloonMin = UInt64(kv["balloon_min"] ?? "") ?? min(512, memMB)
                    let maxMins = Int(kv["max_minutes"] ?? "") ?? 180

                    let diskPath = defaultDiskDirectory
                        .appendingPathComponent("\(vmName).raw")
                        .path
                    let nvramPath = defaultDiskDirectory
                        .appendingPathComponent("\(vmName).nvram")
                        .path

                    let nicMode = NetworkAttachmentMode(rawValue: kv["net.mode"] ?? "") ?? .userSpaceSwitch
                    let nic = NetworkInterfaceSpec(
                        macAddress: kv["net.mac"] ?? MACAddress.deterministicGuestMAC(seed: vmName).description,
                        mode: nicMode,
                        ipv4Address: kv["net.ipv4"] ?? "10.211.55.10",
                        subnetCIDR: kv["net.subnet"] ?? "10.211.55.0/24",
                        gatewayIPv4: kv["net.gateway"] ?? "10.211.55.1"
                    )

                    specs.append(VMSpec(
                        id: vmID,
                        name: vmName,
                        agentOwnerTag: kv["agent_owner"] ?? "imported",
                        guestOS: guestOS,
                        bootLoader: .efiBoot(variableStorePath: nvramPath, createVariableStoreIfMissing: true),
                        compute: CPUAndMemorySpec(
                            vcpuCount: vcpus,
                            memoryMB: memMB,
                            minBalloonMemoryMB: balloonMin
                        ),
                        blockDevices: [
                            BlockDeviceSpec(
                                label: "root",
                                imagePath: diskPath,
                                virtualSizeBytes: 20 * 1024 * 1024 * 1024,
                                isBootVolume: true
                            )
                        ],
                        virtioFSMounts: mounts,
                        networkInterfaces: [nic],
                        portForwards: forwards,
                        maxRuntimeMinutes: maxMins
                    ))
                    currentVMName = nil
                    braceDepth = 0
                }
                continue
            }

            if let eqIdx = trimmed.firstIndex(of: "=") {
                let key = trimmed[..<eqIdx].trimmingCharacters(in: .whitespaces)
                let rawVal = trimmed[trimmed.index(after: eqIdx)...]
                    .trimmingCharacters(in: .whitespaces)
                    .trimmingCharacters(in: CharacterSet(charactersIn: "\""))
                if braceDepth == 2 {
                    nestedKV[key] = rawVal
                } else if braceDepth == 1 {
                    kv[key] = rawVal
                }
            }
        }

        if specs.isEmpty {
            throw AgentVMError.invalidConfiguration(issues: [
                ValidationIssue(
                    fieldPath: "hcl",
                    code: "NO_SANDBOX_VM_BLOCKS",
                    message: "No 'sandbox_vm' definitions found in HCL input.",
                    remediation: "Define at least one 'sandbox_vm \"name\" { ... }' block."
                )
            ])
        }
        return specs
    }

    // MARK: - Export & Import Docker Compose Subset (`compose.yaml`)

    public func exportDockerComposeYAML(vms: [VMSpec]) -> String {
        var lines: [String] = [
            "# Generated by AgentVM IaC Bridge — MicroVM-backed Compose Topology",
            "name: agentvm-fleet",
            "services:"
        ]

        for vm in vms {
            let svc = sanitizeIdentifier(vm.name)
            lines.append("  \(svc):")
            lines.append("    image: agentvm/\(vm.guestOS.rawValue):latest")
            lines.append("    cpus: \(vm.compute.vcpuCount)")
            lines.append("    mem_limit: \(vm.compute.memoryMB)m")
            lines.append("    labels:")
            lines.append("      io.agentvm.owner: \"\(escapeQuoted(vm.agentOwnerTag))\"")

            if !vm.portForwards.isEmpty {
                lines.append("    ports:")
                for fwd in vm.portForwards {
                    lines.append("      - \"\(fwd.hostPort):\(fwd.guestPort)\"")
                }
            }
            if !vm.virtioFSMounts.isEmpty {
                lines.append("    volumes:")
                for m in vm.virtioFSMounts {
                    let roSuffix = m.readOnly ? ":ro" : ""
                    lines.append("      - \"\(ByteMetricsFormatter.scrubHomePath(m.hostDirectoryPath)):\(m.guestMountPoint)\(roSuffix)\"")
                }
            }
        }

        return lines.joined(separator: "\n") + "\n"
    }

    private func sanitizeIdentifier(_ text: String) -> String {
        let allowed = text.lowercased().map { ch -> Character in
            if ch.isLetter || ch.isNumber || ch == "-" || ch == "_" { return ch }
            return "-"
        }
        let str = String(allowed).trimmingCharacters(in: CharacterSet(charactersIn: "-"))
        return str.isEmpty ? "blade" : str
    }

    private func escapeQuoted(_ text: String) -> String {
        text.replacingOccurrences(of: "\\", with: "\\\\")
            .replacingOccurrences(of: "\"", with: "\\\"")
    }

    private func extractQuotedToken(from line: String) -> String? {
        guard let firstQuote = line.firstIndex(of: "\"") else { return nil }
        let rest = line[line.index(after: firstQuote)...]
        guard let secondQuote = rest.firstIndex(of: "\"") else { return nil }
        return String(rest[..<secondQuote])
    }
}
